"""### Plot 5: Confusion matrix (best model)

"""

best_name = results_df.iloc[0]['Model']
best_model = models[best_name]
X_te = X_test.values if best_name in ['Random Forest','Decision Tree','AdaBoost','Gradient Boosting','XGBoost','Naive Bayes'] else X_test_s
y_pred_best = best_model.predict(X_te)
cm = confusion_matrix(y_test, y_pred_best)
plt.figure(figsize=(5, 4))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=['Unstable','Stable'], yticklabels=['Unstable','Stable'])
plt.title(f'Best Model: {best_name}', fontsize=13, fontweight='bold')
